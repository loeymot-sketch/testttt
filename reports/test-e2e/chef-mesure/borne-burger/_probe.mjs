import { chromium } from 'playwright';
const b = await chromium.launch({ headless: true });
const ctx = await b.newContext({ viewport: { width: 1080, height: 1500 }, locale: 'fr-FR' });
const p = await ctx.newPage();
p.setDefaultTimeout(90000); p.setDefaultNavigationTimeout(120000);
await p.emulateMedia({ reducedMotion: 'reduce' });
p.on('console', m => { if (/error|fail|401|token/i.test(m.text())) console.log('CONSOLE', m.type(), m.text().slice(0,200)); });
await p.goto('http://127.0.0.1:8766/kiosk/idle', { waitUntil: 'domcontentloaded' });
await p.evaluate(() => { try { localStorage.clear(); sessionStorage.clear(); } catch(e){} });
await p.goto('http://127.0.0.1:8766/kiosk/idle', { waitUntil: 'domcontentloaded' });
await p.waitForSelector('[data-testid="kiosk-idle-root"]');
await p.waitForTimeout(3000);
const tk = p.locator('[data-testid="kiosk-order-type-takeaway"]');
console.log('takeaway count', await tk.count(), 'visible', await tk.count() ? await tk.first().isVisible() : null);
await p.screenshot({ path: '/tmp/probe-idle.png' });
if (await tk.count()) await tk.first().click({ force: true });
await p.waitForTimeout(6000);
console.log('url après clic', p.url());
await p.screenshot({ path: '/tmp/probe-after.png' });
console.log('body', (await p.locator('body').innerText()).replace(/\s+/g,' ').slice(0,400));
await b.close();
